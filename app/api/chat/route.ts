export async function POST(request: Request) {
  try {
    const { messages, mode } = (await request.json()) as { messages: Array<{ role: string; text: string }>; mode: string }

    if (!messages?.length) return NextResponse.json({ error: "No messages" }, { status: 400 })

    const lastUserMsg = messages[messages.length - 1]?.text || ""
    const lower = lastUserMsg.toLowerCase()

    const matched = REPLIES.filter((r) => r.kw.some((k) => lower.includes(k)))
    const reply = matched.length ? matched[Math.floor(Math.random() * matched.length)] : REPLIES[Math.floor(Math.random() * REPLIES.length)]

    const text = mode === "toxic" ? reply.toxic : reply.heal
    return NextResponse.json({ text })
  } catch (e) {
    console.error("[v0] Chat error:", e)
    return NextResponse.json({ error: "Server error" }, { status: 500 })
  }
}
